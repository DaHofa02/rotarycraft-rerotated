package reika.rotarycraft.content.block;

import net.minecraft.core.BlockPos;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.SimpleMenuProvider;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.phys.BlockHitResult;

import reika.rotarycraft.content.blockentity.CrystallizerBlockEntity;
import reika.rotarycraft.content.menu.CrystallizerMenu;
import reika.rotarycraft.registry.RotaryBlockEntities;

/** Original: MachineRegistry.CRYSTALLIZER in BlockDMIMachine - four directions, opens its GUI on right-click. */
public class CrystallizerBlock extends MachineBlock {

	public CrystallizerBlock(Properties props) {
		super(props, RotaryBlockEntities.CRYSTALLIZER, Placement.FOUR_SIDED, false);
	}

	@Override
	protected InteractionResult useWithoutItem(BlockState state, Level world, BlockPos pos, Player ep, BlockHitResult hit) {
		if (ep.isShiftKeyDown() || !(world.getBlockEntity(pos) instanceof CrystallizerBlockEntity te))
			return InteractionResult.PASS;
		if (!world.isClientSide && ep instanceof ServerPlayer sp && te.isPlayerAccessible(sp))
			sp.openMenu(new SimpleMenuProvider((id, inv, p) -> new CrystallizerMenu(id, inv, te), state.getBlock().getName()), buf -> buf.writeBlockPos(pos));
		return InteractionResult.sidedSuccess(world.isClientSide);
	}
}
