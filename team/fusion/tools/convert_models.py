#!/usr/bin/env python3
"""Mechanically converts original Techne-style model classes (1.7.10 ModelRenderer / LODModelPart) to 1.21.1 ModelPart code.

Geometry is copied 1:1: every box keeps its origin, size, texture offset, mirror flag (as set at addBox time), pivot and rotation.
The render methods are translated statement by statement:
  GL11.glTranslated/f(x, y, z)  -> pose.translate(x, y, z)
  GL11.glRotatef(a, x, y, z)    -> pose.mulPose(TechneModel.rotation(a, x, y, z))
  GL11.glScaled/f(x, y, z)      -> pose.scale(x, y, z)
  Part.render(te, f5)           -> Part.render(pose, vc, light, overlay)
  this.helper(te, ...)          -> this.helper(pose, vc, light, overlay, te, ...)
Anything else that touches GL is reported and must be ported by hand.

Usage: python3 -I tools/convert_models.py <out_dir> <java_package> <base_class_package> <model.java>...
"""
import os
import re
import sys

out_dir, package = sys.argv[1], sys.argv[2]
files = sys.argv[3:]

HEADER = """/*******************************************************************************
 * GENERATED by tools/convert_models.py from the original model class %s. Geometry unchanged.
 * @author Reika Kalseki (original RotaryCraft). Private NeoForge 1.21.1 port; not for distribution.
 ******************************************************************************/
"""

NUM = r"-?[0-9.]+[FfDd]?"


def num(s):
    s = s.strip()
    s = re.sub(r"[FfDd]$", "", s)
    return s + "F" if "." in s or "E" in s else s + "F"


def strip_comments(src):
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    return re.sub(r"//[^\n]*", "", src)


def find_block(src, start):
    """Returns the index just past the closing brace of the block starting at src[start] == '{'."""
    depth = 0
    for i in range(start, len(src)):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError("unbalanced braces")


def parent_source(path, parent):
    """Source of the parent model class: next to the model or in the original's Base package."""
    d = os.path.dirname(os.path.abspath(path))
    while d and os.path.basename(d) != "Models":
        d = os.path.dirname(d)
    if not d:
        return None
    for cand in (os.path.join(os.path.dirname(path), parent + ".java"), os.path.join(os.path.dirname(d), "Base", parent + ".java")):
        if os.path.isfile(cand):
            return strip_comments(open(cand, encoding="utf-8", errors="replace").read())
    return None


def convert(path):
    raw = open(path, encoding="utf-8", errors="replace").read()
    src = strip_comments(raw)
    cls = re.search(r"public\s+(?:abstract\s+)?class\s+(\w+)\s+extends\s+(\w+)", src)
    name, parent = cls.group(1), cls.group(2)
    abstract = "abstract class" in cls.group(0)

    parts = re.findall(r"^\s*(?:protected |private |public )?(?:LODModelPart|ModelRenderer)\s+([\w, ]+);", src, re.M)
    part_names = []
    for p in parts:
        part_names += [x.strip() for x in p.split(",") if x.strip()]

    tw = re.search(r"textureWidth\s*=\s*(\d+)", src)
    th = re.search(r"textureHeight\s*=\s*(\d+)", src)
    if not tw:
        # Inherited from the parent model's constructor (e.g. ModelGearboxBase sets 128x32)
        psrc = parent_source(path, parent)
        if psrc:
            tw = re.search(r"textureWidth\s*=\s*(\d+)", psrc)
            th = re.search(r"textureHeight\s*=\s*(\d+)", psrc)
    tw = int(tw.group(1)) if tw else 64
    th = int(th.group(1)) if th else 32

    # Constructor geometry
    ctor = re.search(r"public\s+%s\s*\([^)]*\)\s*\{" % name, src)
    defs = {}
    order = []
    warnings = []
    supports = []
    if ctor:
        body = src[ctor.end() - 1:find_block(src, ctor.end() - 1)]
        mirror = {}
        supports = []
        for stmt in body.split(";"):
            s = stmt.strip().lstrip("{").strip()
            if re.match(r"(this\.setCompilable|super)\s*\(", s) or "setNewRenderingGroup" in s:
                continue
            m = re.match(r"(?:this\.)?addSupport\s*\(\s*(\w+)\s*\)", s)
            if m:
                supports.append(m.group(1))
                continue
            m = re.match(r"(\w+)\s*=\s*new\s+(?:LODModelPart|ModelRenderer)\s*\(\s*this\s*,\s*(\d+)\s*,\s*(\d+)\s*\)", s)
            if m:
                p = m.group(1)
                defs[p] = {"u": int(m.group(2)), "v": int(m.group(3)), "boxes": [], "pivot": ("0F", "0F", "0F"), "rot": ("0F", "0F", "0F"), "size": None}
                mirror[p] = False
                order.append(p)
                continue
            m = re.match(r"(\w+)\.addBox\s*\(([^)]*)\)", s)
            if m and m.group(1) in defs:
                a = [x.strip() for x in m.group(2).split(",")]
                if len(a) not in (6, 7):
                    warnings.append("addBox with %d args in %s" % (len(a), m.group(1)))
                    continue
                defs[m.group(1)]["boxes"].append(([num(x) for x in a[:3]], [num(x) for x in a[3:6]], num(a[6]) if len(a) == 7 else None, mirror[m.group(1)]))
                continue
            m = re.match(r"(\w+)\.setRotationPoint\s*\(([^)]*)\)", s)
            if m and m.group(1) in defs:
                defs[m.group(1)]["pivot"] = tuple(num(x) for x in m.group(2).split(","))
                continue
            m = re.match(r"(\w+)\.setTextureSize\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)", s)
            if m and m.group(1) in defs:
                defs[m.group(1)]["size"] = (int(m.group(2)), int(m.group(3)))
                continue
            m = re.match(r"(\w+)\.mirror\s*=\s*(true|false)", s)
            if m and m.group(1) in defs:
                mirror[m.group(1)] = m.group(2) == "true"
                continue
            m = re.match(r"this\.setRotation\s*\(\s*(\w+)\s*,([^)]*)\)", s)
            if m and m.group(1) in defs:
                defs[m.group(1)]["rot"] = tuple(num(x) for x in m.group(2).split(","))
                continue
            m = re.match(r"(textureWidth|textureHeight)\s*=", s)
            if m or not s:
                continue
            warnings.append("unhandled constructor statement: " + s[:100])

    sizes = {d["size"] for d in defs.values() if d["size"]}
    if len(sizes) > 1 or (sizes and (tw, th) not in sizes):
        # Techne calls setTextureSize after addBox; a vanilla ModelBox bakes its UVs from the model's size at addBox time,
        # so the per-part size has no effect and the model's declared size is the one that was used in game.
        warnings.append("parts use texture sizes %s after addBox, using the model's %dx%d" % (sizes, tw, th))

    # Methods other than the constructor and setRotationAngles
    methods = []
    for m in re.finditer(r"(?:public|protected|private)\s+(?:final\s+)?void\s+(\w+)\s*\(([^)]*)\)\s*\{", src):
        mname, params = m.group(1), m.group(2)
        if mname in ("setRotationAngles", "render"):
            continue
        end = find_block(src, m.end() - 1)
        body = src[m.end():end - 1]
        methods.append((mname, params, body))

    out = [HEADER % (os.path.basename(path)[:-5]), "package %s;" % package, "",
           "import java.util.List;", "",
           "import com.mojang.blaze3d.vertex.PoseStack;", "import com.mojang.blaze3d.vertex.VertexConsumer;", "",
           "import net.minecraft.client.model.geom.ModelPart;", "import net.minecraft.client.model.geom.PartPose;",
           "import net.minecraft.client.model.geom.builders.CubeDeformation;", "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
           "import net.minecraft.client.model.geom.builders.LayerDefinition;", "import net.minecraft.client.model.geom.builders.MeshDefinition;",
           "import net.minecraft.client.model.geom.builders.PartDefinition;", "import net.minecraft.world.level.block.entity.BlockEntity;", "",
           "@SuppressWarnings(\"unused\")"]
    base = parent if parent not in ("RotaryModelBase", "ModelBase") else "TechneModel"
    out.append("public %sclass %s extends %s {" % ("abstract " if abstract else "", name, base))
    out.append("")
    for p in order:
        out.append("\tprotected final ModelPart %s;" % p)
    out.append("")
    out.append("\tpublic %s(ModelPart root) {" % name)
    out.append("\t\tsuper(root);")
    for p in order:
        out.append('\t\t%s = root.getChild("%s");' % (p, p.lower()))
    for p in supports:
        out.append('\t\tthis.addSupport(%s);' % p)
    out.append("\t}")
    out.append("")
    if not abstract or order:
        out.append("\tpublic static LayerDefinition createLayer() {")
        out.append("\t\tMeshDefinition mesh = new MeshDefinition();")
        out.append("\t\tPartDefinition root = mesh.getRoot();")
        if base != "TechneModel":
            out.append("\t\t%s.addParts(root);" % base)
        out.append("\t\taddParts(root);")
        out.append("\t\treturn LayerDefinition.create(mesh, %d, %d);" % (tw, th))
        out.append("\t}")
        out.append("")
        out.append("\tprotected static void addParts(PartDefinition root) {")
        for p in order:
            d = defs[p]
            b = "CubeListBuilder.create().texOffs(%d, %d)" % (d["u"], d["v"])
            for (o, sz, infl, mir) in d["boxes"]:
                b += ".mirror(%s)" % ("true" if mir else "false")
                if infl and infl not in ("0F", "0.0F"):
                    b += ".addBox(%s, %s, %s, %s, %s, %s, new CubeDeformation(%s))" % (o[0], o[1], o[2], sz[0], sz[1], sz[2], infl)
                else:
                    b += ".addBox(%s, %s, %s, %s, %s, %s)" % (o[0], o[1], o[2], sz[0], sz[1], sz[2])
            out.append('\t\troot.addOrReplaceChild("%s", %s, PartPose.offsetAndRotation(%s, %s, %s, %s, %s, %s));'
                       % (p.lower(), b, d["pivot"][0], d["pivot"][1], d["pivot"][2], d["rot"][0], d["rot"][1], d["rot"][2]))
        out.append("\t}")
        out.append("")

    helpers = {m[0] for m in methods}
    for mname, params, body in methods:
        b = body
        b = re.sub(r"GL11\.glTranslate[df]\s*\(", "pose.translate(", b)
        b = re.sub(r"GL11\.glRotate[df]\s*\(([^;]*)\);", r"pose.mulPose(TechneModel.rotation(\1));", b)
        b = re.sub(r"GL11\.glScale[df]\s*\(", "pose.scale(", b)
        b = re.sub(r"GL11\.glPushMatrix\s*\(\s*\)", "pose.pushPose()", b)
        b = re.sub(r"GL11\.glPopMatrix\s*\(\s*\)", "pose.popPose()", b)
        b = re.sub(r"(\w+)\.render\s*\(\s*te\s*,\s*f5\s*\)", r"\1.render(pose, vc, light, overlay)", b)
        b = re.sub(r"super\.renderAll\s*\(\s*te\s*,", "super.renderAll(pose, vc, light, overlay, te,", b)
        b = re.sub(r"this\.renderList\s*\(\s*te\s*\)", "this.renderAllParts(pose, vc, light, overlay)", b)
        for h in helpers:
            b = re.sub(r"(this\.)?\b%s\s*\(\s*te\b" % h, "this.%s(pose, vc, light, overlay, te" % h, b)
        b = re.sub(r"(\w+)\.setRotationPoint\s*\(", r"\1.setPos(", b)
        # RotaryModelBase.setRenderPass only read MinecraftForgeClient.getRenderPass(); the renderer passes the pass flags instead
        b = re.sub(r"this\.setRenderPass\s*\(\s*\)\s*;", "", b)
        b = re.sub(r"\bForgeDirection\b", "net.minecraft.core.Direction", b)
        b = re.sub(r"(\w+)\.rotateAngle([XYZ])\s*=", lambda m: "%s.%sRot =" % (m.group(1), m.group(2).lower()), b)
        b = re.sub(r"\bArrayList\b", "List<?>", b)
        b = b.replace("LODModelPart.allowCompiling", "false")
        b = b.replace("(TileEntity)", "(BlockEntity)")
        for bad in re.findall(r"GL1[12]\.\w+|Tessellator|ReikaRenderHelper\.\w+|bindTexture\w*", b):
            warnings.append("needs manual port in %s: %s" % (mname, bad))
        p2 = params.replace("TileEntity", "BlockEntity").replace("ArrayList", "List<?>")
        p2 = re.sub(r"List<\?>\s*<[^>]*>", "List<?>", p2)
        p2 = re.sub(r"\bForgeDirection\b", "net.minecraft.core.Direction", p2)
        over = "\t@Override\n" if mname == "renderAll" else ""
        out.append("%s\tpublic void %s(PoseStack pose, VertexConsumer vc, int light, int overlay, %s) {" % (over, mname, p2.strip()))
        out.append(b.rstrip())
        out.append("\t}")
        out.append("")
    out.append("}")
    out.append("")

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, name + ".java"), "w") as f:
        f.write("\n".join(out))
    return name, warnings


for f in files:
    n, w = convert(f)
    print(n, "OK" if not w else "")
    for x in w:
        print("   WARN", x)
